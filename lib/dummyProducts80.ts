export function download80MasterProductsSampleExcel() {
  const worksheet = XLSX.utils.json_to_sheet(DUMMY_80_PRODUCTS_DATA);

  // Set column widths for beautiful layout
  worksheet["!cols"] = [
    { wch: 38 }, // Product Name
    { wch: 22 }, // Category
    { wch: 14 }, // Product Type
    { wch: 55 }, // Description
    { wch: 16 }, // Shortcode
    { wch: 24 }, // SKU
    { wch: 18 }, // Barcode
    { wch: 12 }, // List Price
    { wch: 12 }, // Sales Price
    { wch: 10 }, // Stock
    { wch: 50 }, // Image URL
    { wch: 20 }, // Variation 1 Name
    { wch: 20 }, // Variation 1 Value
    { wch: 20 }, // Variation 2 Name
    { wch: 20 }, // Variation 2 Value
  ];

  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, "Master_Products_80");

  XLSX.writeFile(workbook, "retail_master_80_products_template.xlsx");
}
